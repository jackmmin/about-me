export function getBook(id: string) {
  return BOOK_BY_ID.get(id)
}

// 연속된 절은 묶어서 표기: [1,2,3,5,7,8] → "1-3, 5, 7-8"
export function formatVerses(verses: number[]) {
  const sorted = [...new Set(verses)].sort((a, b) => a - b)
  const parts: string[] = []
  for (let i = 0; i < sorted.length; ) {
    let j = i
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j] + 1) j++
    parts.push(i === j ? `${sorted[i]}` : `${sorted[i]}-${sorted[j]}`)
    i = j + 1
  }
  return parts.join(', ')
}

// "요한복음 3:16-18" / 절을 고르지 않았으면 장 전체 "시편 23편", "요한복음 3장"
export function formatPassage(p: Passage, short = false) {
  const b = getBook(p.book)
  if (!b) return ''
  const name = short ? b.short : b.name
  if (p.verses.length === 0) return `${name} ${p.chapter}${b.id === 'Ps' ? '편' : '장'}`
  return `${name} ${p.chapter}:${formatVerses(p.verses)}`
}

export function formatPassages(passages: Passage[], short = false) {
  return passages.map((p) => formatPassage(p, short)).filter(Boolean).join(' · ')
}
